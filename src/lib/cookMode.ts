import type { BatchPolicy, PreparationMode, Recipe, RecipeBatch, RecipeStep } from '../types'
import { anchorIngredient, baseScaleOf, looksBatchable } from './batchInfo'

/**
 * Две независимые оси: чем определяется количество и как блюдо подготавливают.
 *
 * Три величины, которые приложение раньше считало одной. Сколько съедят — это
 * меню. Сколько купить — это упаковка. Сколько приготовить — это отдельный
 * вопрос, и к первым двум он не сводится. «Йогурт с гранолой и яблоком»
 * предлагал приготовить килограмм на два завтрака по 285 г и 468 г из него
 * «доесть в ближайшие дни» — 841 ккал без человека, дня и приёма пищи. Гранола
 * в этом килограмме размокнет, а яблоко потемнеет.
 *
 * Оси независимы не на словах, и вот два случая, на которых это видно:
 *   Боул с курицей и киноа — компоненты готовят партией под упаковку филе
 *     (`fixedBatch`), а собирают перед едой (`assembleBeforeEating`);
 *   Чиа-пудинг — готовится целиком и заранее (`cookComplete`), но ровно на
 *     запланированные порции (`exactForMenu`).
 * Одной осью такое не описать: пока режим был один, боул и йогурт попадали в
 * одну клетку — и либо оба варились пачкой филе, либо оба теряли партию.
 *
 * Ни одна из осей не выводится по тексту шагов.
 *
 * Количество берётся из подтверждённой партии: партия есть только там, где её
 * кто-то выставил руками (data/verifiedBatches), а по умолчанию блюдо готовится
 * ровно по меню. Так безопаснее: ошибка «приготовили ровно сколько съедят»
 * стоит одной лишней готовки, ошибка «вывели партию по тексту» — килограмма
 * размокшей гранолы. Правило вывода осталось, но только как аудит: оно
 * подсказывает, кому партию стоит подтвердить (`looksBatchable`), и не даёт
 * новому блюду молча её получить.
 *
 * Подготовка берётся у рецепта (`Recipe.preparation`) по той же причине.
 * Правило по тексту живёт здесь же — `suggestedPreparation` — и служит
 * проверкой разметки, а не её источником.
 */

/**
 * Лепка и штучная раскладка: из этого получаются отдельные изделия.
 *
 * `начинить` здесь не случайно: фаршированный перец и печёное яблоко — такие
 * же штуки, как котлета, и округлять их надо до целых, а не до граммов.
 */
const PIECE_WORK = /сформ|слепить|налепить|скатать|начинить|порциями|формочк/i

/** Последний шаг — сборка блюда из частей: «Собрать боул», «Собрать тост». */
const ASSEMBLE = /^соб(рать|ери)/i

/** Последний шаг — убрать заготовку на хранение, а не подать на стол. */
const PUT_AWAY = /переложить в контейнер|убрать в холод/i

/**
 * Приготовление без огня: блендер, настаивание, замачивание, подсушивание.
 * Нужно, чтобы отличить «ничего не готовим, только нарезали» от «готовим, но
 * без плиты» — чиа-пудинг набухает ночь, и это всё-таки приготовление.
 */
const COLD_WORK = /блендер|пробить|взбить|замочить|набух|настоя|подсуш/i

function heated(step: RecipeStep): boolean {
  return step.station === 'stove' || step.station === 'oven'
}

/**
 * Чем меряется количество этого блюда.
 *
 * Считается по самой партии, а не хранится отдельно: `fresh` значит «партии
 * нет», наличие изделий — «партия в штуках», всё остальное — «партия в
 * граммах». Отдельного поля нет намеренно — иначе появилась бы вторая
 * характеристика того же самого, и расходиться они начали бы с первой правки.
 *
 * Замер по базе (78 блюд): 40 с подтверждённой партией — 29 `fixedBatch` и 11
 * `discretePieces`, — и 38 готовятся ровно по меню.
 */
export function batchPolicyOf(batch: RecipeBatch | undefined): BatchPolicy {
  if (!batch || batch.reason === 'fresh') return 'exactForMenu'
  return batch.piece || batch.yieldPieces ? 'discretePieces' : 'fixedBatch'
}

/** Готовим ровно потребность меню — партии у блюда нет. */
export function cooksToOrder(policy: BatchPolicy): boolean {
  return policy === 'exactForMenu'
}

/**
 * Как блюдо подготавливают. Берётся у рецепта; пусто — значит `cookComplete`.
 *
 * Умолчание выбрано самым обычным, а не самым осторожным: «приготовить целиком»
 * — это то, что человек и так сделает, если ему ничего не сказать. Осторожность
 * нужна на другой оси, где цена ошибки в килограммах еды.
 */
export function preparationOf(recipe: Recipe): PreparationMode {
  return recipe.preparation ?? 'cookComplete'
}

/**
 * Что о подготовке говорит текст шагов. Только для аудита разметки.
 *
 * Замер по всей базе (78 блюд). Разметка: 59 `cookComplete`, 9
 * `assembleBeforeEating`, 7 `portionOnly`, 3 `prepareComponents`. Правило
 * совпадает с ней у 77 блюд и расходится у одного — «Яйцо с авокадо»: там
 * сборка стоит в середине строки, «Размять авокадо с лимоном, собрать», и
 * правило её не видит. Разметка от этого не меняется — потому правило и аудит.
 *
 * Отдельно про признак «последний шаг начинается со слова Собрать»: он есть у
 * восьми блюд из 78 и ни разу не срабатывает на блюде с подтверждённой партией
 * — ни один суп, рагу или запеканка им не заканчиваются. Ложных срабатываний по
 * этой оси у него нет вовсе; чего он не ловит — сборку в середине строки.
 */
export function suggestedPreparation(recipe: Recipe): PreparationMode {
  const steps = recipe.steps
  const last = steps[steps.length - 1]?.text ?? ''
  if (ASSEMBLE.test(last)) return 'assembleBeforeEating'
  if (PUT_AWAY.test(last)) return 'prepareComponents'
  if (!steps.some(heated) && !steps.some((s) => COLD_WORK.test(s.text))) return 'portionOnly'
  return 'cookComplete'
}

/**
 * Похоже ли, что блюду нужна подтверждённая партия. Только для аудита.
 *
 * Прежнее правило вывода, дополненное второй осью. Раньше по нему партия и
 * назначалась — и из-за этого йогурт с гранолой получал кастрюлю в четыре доли,
 * а чиа-пудинг — литр овсяного молока. Теперь оно ничего не назначает: по нему
 * проверяется, что список подтверждённых партий не отстал от базы рецептов.
 *
 * Разметка подготовки делает его заметно точнее: собираемое перед едой и
 * раскладываемое по тарелкам кастрюлей не варят, сколько бы дней оно ни
 * хранилось. Замер по базе: без этого условия и с прежним якорным порогом в
 * семь дней правило звало к партии 26 блюд сверх подтверждённых — все каши,
 * салаты и творог с ягодами. Сейчас таких нет ни одного; в обратную сторону
 * остаются два — оба хумуса. Их партию задаёт объём блендера, а этого в тексте
 * шагов нет и взяться ему неоткуда.
 */
export function looksBatchableRecipe(recipe: Recipe): boolean {
  // не доживёт до второго дня — партии быть не может, сколько ни готовь
  if (!looksBatchable(recipe)) return false
  if (recipe.steps.some((s) => PIECE_WORK.test(s.text))) return true
  if (baseScaleOf(recipe, anchorIngredient(recipe)) > 1) return true
  // кастрюля или форма: блюдо доводят до готового вида одной массой и оно ждёт
  return preparationOf(recipe) === 'cookComplete' && recipe.steps.some(heated)
}

