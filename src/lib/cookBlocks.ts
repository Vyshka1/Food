import type { PlannedStep } from '../types'

/**
 * Шаги готовки блоками по времени.
 *
 * Диаграмма отвечает на вопрос «как устроен день», а человек у плиты задаёт
 * другой: «что мне делать сейчас». Полосы и штриховки на этот вопрос не
 * отвечают без расшифровки, поэтому главным на экране стал обычный план по
 * времени: в 11:00 — три действия, в 11:12 — следующие, и так далее.
 *
 * Блок — это то, что делают подряд, не отходя. Он кончается там, где у повара
 * появляется пауза: поставили вариться и ждём. Именно паузу человек и
 * воспринимает как границу «сделал — можно выдохнуть».
 */
export interface CookBlock {
  /** Минуты от старта готовки: когда браться за этот блок. */
  start: number
  steps: PlannedStep[]
  /**
   * К началу блока на плите или в духовке уже что-то идёт само. Отсюда
   * заголовок «Пока всё варится»: это не украшение, а факт про этот момент.
   */
  waiting: boolean
}

/**
 * Пауза, после которой начинается новый блок.
 *
 * Это главное правило по смыслу: граница блока там, где повар отошёл. Но
 * замер показал, что сегодня оно почти не срабатывает — планировщик плотно
 * упаковывает работу и простоя повару не оставляет. 180 планов (20 зёрен × 3
 * набора дней готовки), один повар, потолок 25 минут:
 *
 *   пауза   блоков/план  блоков >7 шагов  одиночных блоков
 *     0 мин     16.0          0%              51%
 *     1 мин      6.7          1%               5%
 *     3 мин      6.6          1%               4%
 *     5 мин      6.6          1%               4%
 *    10 мин      6.6          1%               4%
 *   999 мин      6.5          1%               3%
 *
 * От минуты и выше — одна и та же раскладка: настоящих пауз в этих планах
 * нет. Ноль не годится: тогда границей становится любой сдвиг на секунды, и
 * половина блоков вырождается в заголовок над одним шагом. Пять — пауза,
 * которую человек действительно заметил бы; на планах с долгим томлением
 * правило сработает по делу, а на нынешних просто молчит.
 */
export const BLOCK_GAP_MINUTES = 5

/**
 * Сколько блок может тянуться, даже если пауз в нём нет.
 *
 * Раз пауз нет, всю работу делает именно потолок — и это его замер, тот же
 * набор планов, пауза 5 минут:
 *
 *   потолок  блоков/план  блоков >7 шагов  одиночных блоков
 *    10 мин      12.3          0%              29%
 *    15 мин       9.4          0%              14%
 *    20 мин       7.8          0%               7%
 *    25 мин       6.6          1%               4%
 *    40 мин       4.6         15%               5%
 *   без него      1.1         91%               2%
 *
 * Без потолка девять блоков из десяти длиннее семи шагов — то есть экран
 * снова превращается в один список, ради ухода от которого всё и затевалось.
 * На сорока минутах длинных уже шестая часть. Двадцать пять — последняя
 * точка, где длинных почти нет, а заголовков ещё не больше, чем шагов.
 *
 * Замер выше сделан до того, как появился потолок по шагам (BLOCK_MAX_STEPS);
 * длинные блоки теперь режет он. Но минуты этот потолок держит по-прежнему:
 * с ним, но без потолка по времени, блок у одного повара тянется 22 минуты по
 * медиане и до 47 в максимуме. «В 11:00 сделайте это» не должно означать
 * «и дальше ещё три четверти часа».
 */
export const BLOCK_SPAN_MINUTES = 25

/**
 * Отдельный, более тесный потолок для первого блока.
 *
 * «Начните с этих шести шагов» — неправда, если эти шесть растянуты на
 * двадцать две минуты. Без отдельного потолка первый блок именно такой: у
 * одного повара он тянется 22 минуты по медиане (до 44) — то есть четверть
 * всей готовки под заголовком «начните».
 *
 * Замер на тех же 400 планах, потолок шагов включён. Шаги в первом блоке и
 * его длина, медиана и максимум:
 *
 *   потолок   один повар            вдвоём
 *              шагов   минут        шагов   минут
 *     3 мин     2 / 5   0 / 0        3 / 6   0 / 0
 *     5 мин     3 / 5   0 / 4        4 / 6   0 / 4
 *     8 мин     3 / 5   0 / 4        4 / 6   0 / 6
 *    12 мин     4 / 5   4 / 8        5 / 6   6 / 10
 *   без него    5 / 6  22 / 44       5 / 7   8 / 20
 *
 * Восемь минут: до двенадцати картина держится, а на двенадцати первый блок
 * по медиане уже растягивается на несколько минут и набирает пять шагов —
 * снова список вместо «поставьте это сейчас». Меньше пяти отрезать нечего:
 * планировщик и так ставит первые кастрюли подряд, в одну и ту же минуту.
 */
export const FIRST_BLOCK_MINUTES = 8

/**
 * Сколько шагов помещается в один блок.
 *
 * Потолок по минутам молчаливо считал, что за минуту делается одно дело. Это
 * верно для одного повара, но вдвоём в те же 25 минут влезает вдвое больше
 * работы — и блок снова становится длинным списком. Замер на 400 планах
 * (семья из двух едоков, наборы дней готовки [0,3] [1,4] [2,6] [0,2,4] [3]
 * [0] [5] [1,3,5], зёрна 1..20, все дни готовки каждой недели):
 *
 *   потолок   один повар                вдвоём
 *             блоков  >7 шагов  первый  блоков  >7 шагов  первый
 *     4 шага    6.7      0%       до 5    6.2      0%       до 6
 *     5 шагов   6.2      0%       до 5    5.5      0%       до 6
 *     6 шагов   6.0      0%       до 7    5.1      1%       до 6
 *     7 шагов   6.0      0%       до 7    4.8      5%       до 8
 *   без него    6.0      0%       до 7    4.5     20%       до 9
 *
 * Без потолка по шагам вдвоём каждый пятый блок длиннее семи шагов, а первый
 * доходит до девяти — ровно та стена текста, от которой уходили. Пять:
 * длинных блоков в этом наборе не встречается ни у одного повара, ни у
 * двоих, а заголовков прибавляется немного (6.0 → 6.2 у одного повара).
 *
 * Потолок не разрывает одну минуту: если следующий шаг начинается тогда же,
 * когда предыдущий, он остаётся в том же блоке. Поэтому блок иногда чуть
 * длиннее пяти — в замере до шести, — и на других планах исключение может
 * дать блок длиннее семи. Это цена того, что «в 11:12» не разъезжается на
 * два заголовка.
 */
export const BLOCK_MAX_STEPS = 5

export function cookBlocks(steps: PlannedStep[]): CookBlock[] {
  const ordered = [...steps].sort((a, b) => a.start - b.start || a.end - b.end)
  const blocks: CookBlock[] = []

  for (const step of ordered) {
    const block = blocks[blocks.length - 1]
    if (!block) {
      blocks.push({ start: step.start, steps: [step], waiting: false })
      continue
    }
    // конец последней занятости в блоке: от него и меряется пауза
    const busyUntil = Math.max(...block.steps.map((s) => s.start + Math.max(1, s.activeMinutes)))
    const idle = step.start - busyUntil
    const span = step.start - block.start
    // первый блок — это «поставьте сейчас», и он обязан быть коротким
    const cap = blocks.length === 1 ? FIRST_BLOCK_MINUTES : BLOCK_SPAN_MINUTES
    // потолок по шагам, но не посреди одной минуты: см. BLOCK_MAX_STEPS
    const last = block.steps[block.steps.length - 1]
    const full = block.steps.length >= BLOCK_MAX_STEPS && step.start > last.start
    if (idle >= BLOCK_GAP_MINUTES || span >= cap || full) {
      blocks.push({ start: step.start, steps: [step], waiting: false })
    } else {
      block.steps.push(step)
    }
  }

  /*
   * «Пока всё варится» — правда или нет, решаем по самим шагам, а не по
   * порядковому номеру блока: к его началу что-то из прежнего ещё не
   * закончилось и идёт само.
   */
  for (const block of blocks) {
    block.waiting = ordered.some(
      (s) => s.unattended && s.start < block.start && s.end > block.start,
    )
  }
  return blocks
}

/** Заголовок блока: что это за момент готовки. */
export function blockTitle(block: CookBlock, index: number, total: number): string {
  if (index === 0) {
    const n = block.steps.length
    const word = n === 2 ? 'этих двух шагов' : n === 3 ? 'этих трёх шагов' : `этих ${n} шагов`
    return n === 1 ? 'Начните с первого шага' : `Начните с ${word}`
  }
  if (index === total - 1) return 'Заканчиваем'
  return block.waiting ? 'Пока всё варится' : 'Готовим дальше'
}

/**
 * Подзаголовок блока.
 *
 * Про первый блок нельзя писать «одновременно», когда повар один: три
 * кастрюли он всё равно ставит по очереди, и обещание, которого нельзя
 * выполнить, — худший вид подсказки. Вдвоём — можно, и тогда это сказано.
 */
export function blockHint(block: CookBlock, index: number, total: number, cooks: number): string {
  if (index === 0) {
    return cooks > 1
      ? 'Разделите между собой — вас двое.'
      : 'Выполните по порядку в первые минуты.'
  }
  if (index === total - 1) return 'Последние действия этого дня.'
  return block.waiting
    ? 'Займитесь подготовкой — это удобно делать сейчас.'
    : 'Основная готовка по плану.'
}
