/**
 * Зерно недели — из её даты, а не из случайности.
 *
 * Меню собирается детерминированно: одинаковое зерно при одинаковой анкете
 * даёт одинаковую неделю. Раньше зерно новой недели бралось случайным, и это
 * было незаметно ровно до тех пор, пока следующую неделю нельзя было увидеть
 * заранее. Как только её показали, случайность превратилась в обман: человек
 * посмотрел в воскресенье одно, а в понедельник приложение собрало другое —
 * и готовка, затеянная под увиденное меню, оказалась не к нему.
 *
 * Поэтому зерно выводится из понедельника недели. Тогда предпросмотр и
 * настоящая сборка — это один и тот же вызов с одними и теми же входными
 * данными, а не два похожих.
 *
 * Разнообразие от этого не страдает: у каждой недели своя дата, значит и своё
 * зерно, и соседние недели расходятся так же, как расходились случайные.
 */

/**
 * FNV-1a, 32 бита.
 *
 * Криптография тут ни при чём, нужна ровно одна вещь: соседние даты, которые
 * отличаются одной цифрой, должны давать непохожие числа. Простое сложение
 * кодов символов этого не даёт — понедельники подряд шли бы соседними
 * зёрнами, а близкие зёрна mulberry32 разводит не сразу.
 */
export function weekSeed(weekStart: string): number {
  let hash = 0x811c9dc5
  for (let i = 0; i < weekStart.length; i++) {
    hash ^= weekStart.charCodeAt(i)
    // умножение с переполнением как в C: Math.imul, а не `*`
    hash = Math.imul(hash, 0x01000193)
  }
  return hash >>> 0
}
